inline uint8_t GridsMix(uint8_t a, uint8_t b, uint8_t bal) // U8Mix
{ return (uint8_t)(((uint16_t)a * (255 - bal) + (uint16_t)b * bal) >> 8); }

// step 0..31, instrument 0..2, x/y 0..255 (Grids map coordinates)
inline uint8_t GridsReadDrumMap(uint8_t step, uint8_t instrument, uint8_t x, uint8_t y)
{
    uint8_t i = x >> 6, j = y >> 6;
    if(i > 3) i = 3; if(j > 3) j = 3;
    const uint8_t* a = kGridsNodes[kGridsMap[i][j]];
    const uint8_t* b = kGridsNodes[kGridsMap[i + 1][j]];
    const uint8_t* c = kGridsNodes[kGridsMap[i][j + 1]];
    const uint8_t* d = kGridsNodes[kGridsMap[i + 1][j + 1]];
    uint8_t off = (uint8_t)(instrument * kGridsSteps + step);
    uint8_t bx = (uint8_t)(x << 2), by = (uint8_t)(y << 2);
    return GridsMix(GridsMix(a[off], b[off], bx), GridsMix(c[off], d[off], bx), by);
}

