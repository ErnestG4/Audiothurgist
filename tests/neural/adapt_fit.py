#!/usr/bin/env python3
"""Fit the Adaptive lens's anchor space (core/bb_classify_anchors.h) from a feature dump of the TRAINING sample:
  classify_bench --truth adt.csv --root <breaks> --sample 200 --seed 2 --modes 04 --dump train.csv
Statistics come from every sounding hit step with a truth class (kick / snare / hat); files named in the
exclusion dumps (the measurement sets) are dropped first. Writes μ, σ per feature and the three class means in
z-space. Also prints the supervised ceiling (5-fold LDA) so the lens's unsupervised result can be read against it.
Usage: adapt_fit.py train.csv out.h [exclude1.csv exclude2.csv ...]"""
import sys, pandas as pd, numpy as np
from sklearn.discriminant_analysis import LinearDiscriminantAnalysis
from sklearn.model_selection import cross_val_score
d = pd.read_csv(sys.argv[1]); out = sys.argv[2]
excl = set()
for p in sys.argv[3:]: excl |= set(pd.read_csv(p).file.unique())
d = d[~d.file.isin(excl)]
F = [f'f{j}' for j in range(18)]
h = d[(d.hit == 1) & (d.truth < 3)].copy()
print(f"{d.file.nunique()} training files after exclusion, {len(h)} hit steps with truth, classes {h.truth.value_counts().sort_index().tolist()}")
mu = h[F].mean().values.copy(); sd = h[F].std().values.copy() + 1e-6
# the two decay features are only defined where a late window existed
for j in (16, 17):
    v = h[h.lateok == 1][F[j]]; mu[j] = v.mean(); sd[j] = v.std() + 1e-6
z = (h[F].values - mu) / sd
z[h.lateok.values == 0, 16:] = 0
anch = np.stack([z[h.truth.values == c].mean(axis=0) for c in range(3)])
# diagonal metric for the nearest-anchor rule: coordinate descent on the training accuracy (a few
# rounds over a small grid; the lens's k-means then runs in this weighted space)
y = h.truth.values
def na(w): return np.argmin((((z[:, None, :] - anch[None]) * w) ** 2).sum(-1), axis=1)
w = np.ones(18); best = (na(w) == y).mean()
for _ in range(3):
    for j in range(18):
        for cand in (0, 0.25, 0.5, 1, 1.5, 2, 3):
            w2 = w.copy(); w2[j] = cand; a = (na(w2) == y).mean()
            if a > best + 1e-4: best, w = a, w2
with open(out, 'w') as fo:
    fo.write("#pragma once\n// CLASSIFY: the Adaptive lens's anchor space — generated by tests/neural/adapt_fit.py from a\n"
             f"// 200-break training sample ({d.file.nunique()} files after excluding the measurement sets), neural hit\n"
             "// labels (ADTOF). Do not edit by hand; refit when the features change.\nnamespace bb {\n")
    fo.write("constexpr float kAdaptMu[18] = {" + ", ".join(f"{v:.4f}f" for v in mu) + "};\n")
    fo.write("constexpr float kAdaptSd[18] = {" + ", ".join(f"{v:.4f}f" for v in sd) + "};\n")
    fo.write("constexpr float kAdaptAnchor[3][18] = {\n" + ",\n".join("    {" + ", ".join(f"{v:.4f}f" for v in row) + "}" for row in anch) + "};\n")
    fo.write("constexpr float kAdaptWFit[18] = {" + ", ".join(f"{v:.2f}f" for v in w) + "};\n}\n")
print("anchors (z-space):"); print(np.round(anch, 2))
print("weights:", w)
print("training hit steps: Hockman %.3f, nearest anchor unweighted %.3f, weighted %.3f, LDA 5-fold ceiling %.3f" % (
    (h.hock == h.truth).mean(), (na(np.ones(18)) == y).mean(), best, cross_val_score(LinearDiscriminantAnalysis(), z, y, cv=5).mean()))
